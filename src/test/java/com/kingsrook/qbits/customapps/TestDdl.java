package com.kingsrook.qbits.customapps;


import java.util.ArrayList;
import java.util.List;
import com.kingsrook.qqq.backend.core.model.metadata.fields.QFieldMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.tables.QTableMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.tables.UniqueKey;


/*******************************************************************************
 ** PostgreSQL DDL derived from QQQ table metadata (exact, quoted names, as QQQ
 ** quotes them), so a test schema is exactly what the producer defined.
 *******************************************************************************/
final class TestDdl
{
   /*******************************************************************************
    ** Utility class.
    *******************************************************************************/
   private TestDdl()
   {
   }



   /*******************************************************************************
    ** One CREATE TABLE.
    *******************************************************************************/
   static String create(QTableMetaData table)
   {
      List<String> lines = new ArrayList<>();
      for(QFieldMetaData field : table.getFields().values())
      {
         lines.add("   \"" + field.getName() + "\" " + type(table, field));
      }
      for(UniqueKey key : table.getUniqueKeys() == null ? List.<UniqueKey>of() : table.getUniqueKeys())
      {
         lines.add("   UNIQUE (" + String.join(", ", key.getFieldNames().stream().map(n -> "\"" + n + "\"").toList()) + ")");
      }
      return "CREATE TABLE \"" + table.getName() + "\" (\n" + String.join(",\n", lines) + "\n)";
   }



   /*******************************************************************************
    ** Column type and constraints.
    *******************************************************************************/
   private static String type(QTableMetaData table, QFieldMetaData field)
   {
      if(field.getName().equals(table.getPrimaryKeyField()))
      {
         return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
      }
      String base = switch(field.getType())
      {
         case STRING, PASSWORD -> field.getMaxLength() == null ? "TEXT" : "VARCHAR(" + field.getMaxLength() + ")";
         case TEXT, HTML -> "TEXT";
         case INTEGER -> "INTEGER";
         case LONG -> "BIGINT";
         case BOOLEAN -> "BOOLEAN";
         case DATE_TIME -> "TIMESTAMP WITH TIME ZONE";
         default -> throw new IllegalStateException("Unsupported type " + field.getType());
      };
      return base + (Boolean.TRUE.equals(field.getIsRequired()) ? " NOT NULL" : "");
   }
}
